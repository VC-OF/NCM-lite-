"""
Test live interactive NCM Studio server via HTTP on port 8000.
"""

import urllib.request
import json
import time

def test_interactive_api(prompt, target_bytes, temp=0.75, top_k=35, top_p=0.90):
    url = "http://127.0.0.1:8000/api/generate"
    payload = {
        "prompt": prompt,
        "target_bytes": target_bytes,
        "temperature": temp,
        "top_k": top_k,
        "top_p": top_p
    }
    req = urllib.request.Request(
        url,
        data=json.dumps(payload).encode("utf-8"),
        headers={"Content-Type": "application/json"}
    )
    t0 = time.perf_counter()
    with urllib.request.urlopen(req, timeout=45) as res:
        data = json.loads(res.read().decode("utf-8"))
    client_elapsed = time.perf_counter() - t0
    return data, client_elapsed


def main():
    print("=" * 76)
    print("LIVE INTERACTIVE HTTP API BENCHMARK (http://127.0.0.1:8000)")
    print("=" * 76)

    tests = [
        ("Standard 256B Sequence (K=3 Parallel Passes)", "Once upon a time, Lily found a ", 256),
        ("Chained 512B Long Story (Sliding Window)", "Tim and his dog Spot ran to the ", 512),
        ("Multi-Paragraph 1024B Full Story", "One sunny morning, the little bird ", 1024)
    ]

    for title, prompt, length in tests:
        print(f"\n[*] Testing: {title}")
        print(f"  • Prompt: \"{prompt}\"")
        print(f"  • Requested Length: {length} bytes")

        data, client_time = test_interactive_api(prompt, length)

        print(f"  • Server Latency: {data['latency_seconds'] * 1000:.1f} ms")
        print(f"  • Server Throughput: {data['throughput_bytes_per_sec']:.1f} bytes/s")
        actual_bytes = data.get("actual_bytes", len(data["final_text"].encode("utf-8")))
        print(f"  • Actual Generated Bytes: {actual_bytes}")
        print(f"  • Client Roundtrip Time: {client_time * 1000:.1f} ms")
        print("  • Decoded Final Text Sample:")
        print("    \"" + data["final_text"][:220].replace("\n", " ") + "...\"")

        if length == 256:
            print("  • Level 1 Coarse Sketch (ell_1 = 64 tokens):")
            print("    \"" + data["level_1_text"][:120].replace("\n", " ") + "...\"")
            print("  • Level 2 Intermediate Refinement (ell_2 = 128 tokens):")
            print("    \"" + data["level_2_text"][:120].replace("\n", " ") + "...\"")

    print("\n" + "=" * 76)
    print("ALL INTERACTIVE HTTP SERVER TESTS COMPLETED SUCCESSFULLY!")
    print("=" * 76)


if __name__ == "__main__":
    main()
