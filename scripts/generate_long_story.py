"""
Generate Multi-Paragraph Long Stories with NCM-Lite.
Uses sliding-window autoregressive chaining across K=3 parallel generation blocks.
"""

import os
import sys
import argparse
import time

base_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if base_dir not in sys.path:
    sys.path.insert(0, base_dir)
src_dir = os.path.join(base_dir, "src")
if src_dir not in sys.path:
    sys.path.insert(0, src_dir)

import torch
from ncm.tokenizer.model import TokenizerModel
from ncm.models.next_concept import NextConceptTransformer
from ncm.training.checkpoint import CheckpointManager
from ncm.inference.generate import generate_chained_sequence


def main():
    parser = argparse.ArgumentParser(description="Generate long stories with NCM-Lite sliding-window chaining.")
    parser.add_argument("--prompt", type=str, default="Once upon a time, Lily found a little ",
                        help="Opening story prompt.")
    parser.add_argument("--length", type=int, default=512, choices=[256, 512, 768, 1024],
                        help="Target total length in bytes (default: 512).")
    parser.add_argument("--temp", type=float, default=0.75, help="Sampling temperature.")
    parser.add_argument("--top_k", type=int, default=35, help="Top-k filtering threshold.")
    parser.add_argument("--top_p", type=float, default=0.90, help="Top-p nucleus threshold.")
    args = parser.parse_args()

    device = "cpu"
    print("=" * 76)
    print("NCM-LITE: MULTI-PARAGRAPH LONG STORY GENERATION (SLIDING WINDOW)")
    print("=" * 76)

    # 1. Load checkpoints
    ckpt_dir = os.path.join(base_dir, "checkpoints")
    gen_ckpt = os.path.join(ckpt_dir, "ncm_real_text_model.pt")
    tok_ckpt = os.path.join(ckpt_dir, "ncm_real_text_tokenizer.pt")

    if not os.path.exists(gen_ckpt) or not os.path.exists(tok_ckpt):
        raise FileNotFoundError("Checkpoints not found in checkpoints/. Run training first.")

    print(f"[*] Initializing models on {device}...")
    tokenizer = TokenizerModel(vocab_size=256, embed_dim=64, max_seq_len=256,
                               num_levels=3, levels=[64, 128, 256], codebook_size=256).to(device)
    generator = NextConceptTransformer(num_levels=3, levels=[64, 128, 256], codebook_size=256,
                                       latent_dim=64, embed_dim=384, num_layers=6, num_heads=6,
                                       intermediate_dim=1536).to(device)

    CheckpointManager.load(gen_ckpt, model=generator, device=device)
    CheckpointManager.load(tok_ckpt, model=tokenizer, device=device)
    generator.eval()
    tokenizer.eval()

    num_windows = (args.length - 256) // (256 - 64) + 1
    print(f"[+] Loaded trained models successfully.")
    print(f"  • Opening Prompt: \"{args.prompt}\"")
    print(f"  • Target Length:  {args.length} bytes (~{num_windows} chained NCM windows)")
    print(f"  • Sampling:       Temp={args.temp}, Top-k={args.top_k}, Top-p={args.top_p}")

    print("\n[*] Generating multi-paragraph story...")
    t0 = time.perf_counter()
    story = generate_chained_sequence(
        generator=generator,
        tokenizer=tokenizer,
        prompt=args.prompt,
        target_bytes=args.length,
        overlap_bytes=64,
        temperature=args.temp,
        top_k=args.top_k,
        top_p=args.top_p,
        device=device
    )
    elapsed = time.perf_counter() - t0

    print("-" * 76)
    print("GENERATED STORY OUTPUT:")
    print("-" * 76)
    print(story)
    print("-" * 76)
    print(f"Metrics:")
    print(f"  • Total Generated Bytes: {len(story.encode('utf-8'))}")
    print(f"  • Total Wall Time:       {elapsed:.3f}s")
    print(f"  • Generation Throughput: {len(story.encode('utf-8')) / elapsed:.1f} bytes/s")
    print("=" * 76)


if __name__ == "__main__":
    main()
